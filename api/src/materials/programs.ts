// Темы класса с линиями печатаются по линиям: тема без линии выпала бы молча.
for (const subjects of Object.values(PROGRAMS)) {
  for (const [subject, grades] of Object.entries(subjects)) {
    for (const [grade, { topics }] of Object.entries(grades)) {
      const lost = topics.some((t) => t.line) ? topics.filter((t) => !t.line) : []
      if (lost.length) {
        throw new Error(`Программа «${subject}, ${grade} класс»: у темы «${lost[0].title}» не указана линия`)
      }
    }
  }
}

function topicLine(t: Topic, n: number): string {
  return `${n}. ${t.title}: ${t.content}.` + (t.extra ? ` Вне обычной программы: ${t.extra}.` : '')
}

/**
 * Блок для промпта или null, если карточки программы для ученика нет.
 */
export function program(country: Country, subject: string, grade: number | null): string | null {
  const subjectPrograms = PROGRAMS[country]?.[subject]
  const current = grade ? subjectPrograms?.[grade] : undefined
  if (!grade || !current) return null

  const parallel = current.topics.some((t) => t.line)
  const lines = parallel
    ? (['алгебра', 'геометрия'] as const).flatMap((line) => {
        const topics = current.topics.filter((t) => t.line === line)
        return [`${line === 'алгебра' ? 'Алгебра' : 'Геометрия'}:`, ...topics.map((t, i) => topicLine(t, i + 1))]
      })
    : current.topics.map((t, i) => topicLine(t, i + 1))

  const previous = subjectPrograms?.[grade - 1]
  return [
    `Учебная программа ученика — ${subject.toLowerCase()}, ${grade} класс. Темы идут в том порядке, в каком их проходят в школе` +
      (parallel ? '; алгебру и геометрию ведут параллельно, порядок действует внутри каждой линии' : '') +
      '. Программа определяет, какие темы входят в класс и на что можно опираться. ' +
      'Найди тему урока: всё, что стоит раньше, ученик уже знает, на это можно опираться; того, что стоит позже, он ещё не проходил — не используй это в объяснении и в заданиях. Если темы урока в списке нет, репетитор идёт не по программе класса: раскрой тему как есть. ' +
      'Термины бери из программы и не заменяй их своими словами, в том числе в заголовках. То, что помечено «вне обычной программы», давай, только если тема урока прямо об этом. Всё это — сведения для тебя: в материале не упоминай программу, учебник и то, чего ученик ещё не проходил.',
    ...lines,
    current.advanced ? `На повышенном уровне ${current.advanced}. Уровень ученика неизвестен: материал повышенного уровня давай, только если тема урока прямо о нём.` : null,
    current.note,
    previous ? `В ${grade - 1} классе пройдено: ${previous.topics.map((t) => t.title.toLowerCase()).join('; ')}.` : null,
  ]
    .filter(Boolean)
    .join('\n')
}
