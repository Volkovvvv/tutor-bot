/** «10 класс · ЕГЭ», «8 класс», «ЦЭ» или null. */
export function levelLabel(grade: number | null, goal: StudyGoal): string | null {
  return [grade ? `${grade} класс` : null, GOAL_LABELS[goal]].filter(Boolean).join(' · ') || null
}

