import { codeNotes, mergeNotes } from './answer-check'
import { mathCheck } from './math-check'

const ok = { ok: true }
const note = (task: string, key: string, result?: string) => {
  const verdict = mathCheck(task, key, result)
  return verdict && !verdict.ok ? verdict.note : verdict
}

describe('mathCheck: неравенства', () => {
  it('подтверждает верный ключ', () => {
    expect(mathCheck('Реши неравенство (x − 2)(x − 7) > 0.', 'x < 2 или x > 7. Корни — 2 и 7.')).toEqual(ok)
    expect(mathCheck('Найди все значения x, при которых −x² + 4x + 5 ≥ 0.', '−1 ≤ x ≤ 5. Корни — −1 и 5.')).toEqual(ok)
    expect(mathCheck('Реши неравенство x² − 9 < 0.', 'x принадлежит (−3; 3).')).toEqual(ok)
  })

  it('берёт ответ после «Ответ:», а не первое предложение решения', () => {
    const key = '1) Найди корни: x² − x − 6 = (x + 2)(x − 3).\n2) Проверь знаки.\n3) Ответ: −2 < x < 3.'
    expect(mathCheck('Реши неравенство x² − x − 6 < 0.', key)).toEqual(ok)
    expect(mathCheck('Реши неравенство 2x² − 3x − 5 ≤ 0.', 'D = 49; корни x₁ = −1 и x₂ = 2,5; ответ: −1 ≤ x ≤ 2,5.')).toEqual(ok)
  })

  it('знает «любое число» и «решений нет»', () => {
    expect(mathCheck('Найди все решения неравенства x² + 2x + 5 > 0.', 'Любое действительное число. D < 0.')).toEqual(ok)
    expect(mathCheck('Реши неравенство x² + 1 < 0.', 'Решений нет.')).toEqual(ok)
    expect(note('Реши неравенство (x + 3)² ≤ 0.', 'Решений нет.')).toBe(
      'Подстановка: x = −3 подходит под условие, а в ответ не входит.',
    )
  })

  it('ловит перепутанные промежутки и границы', () => {
    expect(note('Реши неравенство (x − 2)(x − 7) > 0.', '2 < x < 7.')).toBe(
      'Подстановка: x = 0 подходит под условие, а в ответ не входит.',
    )
    // Строгий знак вместо нестрогого виден только на самой границе
    expect(note('Найди все значения x, при которых −x² + 4x + 5 ≥ 0.', '−1 < x < 5.')).toBe(
      'Подстановка: x = −1 подходит под условие, а в ответ не входит.',
    )
    // Знаменатель обращается в ноль: −2 в ответ входить не может
    expect(note('Реши неравенство (x − 1)/(x + 2) ≥ 0.', 'x ≤ −2 или x ≥ 1.')).toBe(
      'Подстановка: x = −2 входит в ответ, а условию не удовлетворяет.',
    )
    expect(mathCheck('Реши неравенство (x − 1)/(x + 2) ≥ 0.', 'x < −2 или x ≥ 1.')).toEqual(ok)
  })

  it('сверяет вариант ответа по номеру', () => {
    const task =
      'Укажи решение неравенства x² − 8x + 12 ≤ 0.\n1) x ≤ 2 или x ≥ 6\n2) 2 < x < 6\n3) 2 ≤ x ≤ 6\n4) x < 2 или x > 6\nВ ответ запиши номер варианта.'
    expect(mathCheck(task, '3. Корни — 2 и 6.')).toEqual(ok)
    expect(note(task, '2.')).toBe('Подстановка: x = 2 подходит под условие, а в вариант 2 не входит.')
    expect(note(task.replace('2) 2 < x < 6', '2) 6 ≥ x ≥ 2'), '3.')).toBe('Подстановкой подходят два варианта: 2 и 3.')
  })
})

describe('mathCheck: уравнения', () => {
  it('подтверждает корни в разной записи', () => {
    expect(mathCheck('Реши уравнение x² − 5x + 6 = 0.', 'x₁ = 2, x₂ = 3. По теореме Виета.')).toEqual(ok)
    expect(mathCheck('Реши уравнение x² − 5x + 6 = 0.', '2 и 3.')).toEqual(ok)
    expect(mathCheck('Реши уравнение x² = 16.', 'x = ±4.')).toEqual(ok)
    expect(mathCheck('Реши уравнение 2x + 3 = 11.', '4. Переносим 3 вправо.')).toEqual(ok)
    expect(mathCheck('Реши уравнение |x − 2| = 5.', 'x = 7 или x = −3.')).toEqual(ok)
    expect(mathCheck('Реши уравнение √(x + 1) = 3.', 'x = 8.')).toEqual(ok)
    expect(mathCheck('Реши уравнение log₄ x = 3.', 'x = 4³ = 64.')).toEqual(ok)
  })

  it('ловит неверный, потерянный и посторонний корень', () => {
    expect(note('Реши уравнение x² − 5x + 6 = 0.', 'x = 2 или x = 4.')).toBe(
      'Подстановка: x = 3 подходит под условие, а в ответ не входит.',
    )
    expect(note('Реши уравнение x² = 16.', 'x = 4.')).toBe('Подстановка: x = −4 подходит под условие, а в ответ не входит.')
    // Посторонний корень: при x = −3 под логарифмом отрицательное число
    expect(note('Реши уравнение log₂(x − 1) + log₂(x + 1) = 3.', 'x = 3 или x = −3.')).toBe(
      'Подстановка: x = −3 входит в ответ, а условию не удовлетворяет.',
    )
  })
})

describe('mathCheck: вычисления', () => {
  it('считает дроби и смешанные числа по школьным правилам', () => {
    expect(mathCheck('Вычисли: 3/4 + 1/6.', '11/12. Общий знаменатель 12.')).toEqual(ok)
    // Дробь считается раньше деления: (3/4) : (1/2), а не 3 : 4 : 1 : 2
    expect(mathCheck('Вычисли: 3/4 : 1/2.', '1 1/2.')).toEqual(ok)
    expect(mathCheck('Найди значение выражения 2,5 · 4 − 3².', '2,5 · 4 − 9 = 10 − 9 = 1.')).toEqual(ok)
  })

  it('ловит ошибку в счёте', () => {
    expect(note('Найди значение выражения 2,5 · 4 − 3².', '2.')).toBe('Пересчёт даёт 1, а в ключе 2.')
  })
})

describe('mathCheck: за что не берётся', () => {
  it.each([
    // Слово меняет вопрос: ответ — не множество решений
    ['Найди положительный корень уравнения x² = 16.', 'x = 4.'],
    ['Найди сумму натуральных решений неравенства x² − 9 < 0.', '3.'],
    ['Найди наибольшее решение неравенства x² − 9 ≤ 0.', '3.'],
    // Система с двумя решениями: подстановка подтвердит одно, а второе не увидит
    ['Реши систему уравнений: x + y = 5, xy = 6.', 'x = 2, y = 3.'],
    // Английский: скобки и «…» похожи на формулу только издали
    ['Раскрой скобки: She … (never / try) sushi.', 'has never tried.'],
    // Текстовая задача и геометрия
    ['Тело массой m = 2 кг движется с ускорением 3 м/с². Найди силу.', 'F = 6 Н.'],
    ['В треугольнике ABC сторона AB = 5 см. Найди BC.', 'BC = 5 см.'],
    // Две переменные, параметр
    ['Реши уравнение x + y = 5.', 'x = 2, y = 3.'],
    // Ответ записан так, что код его не читает
    ['Реши уравнение x² − 5x + 6 = 0.', 'Раскладываем на множители и получаем два корня.'],
    ['Реши неравенство x² − 9 < 0.', '−3 < x < 3, x ≠ 0.'],
    ['Вычисли: 1/3 + 1/3.', '≈ 0,67.'],
    // Первое предложение ключа — шаг решения, а не итог
    ['Реши уравнение log₂(x² − 5x + 6) = 1. В ответе укажи наибольший корень.', 'x² − 5x + 6 = 2, значит, x² − 5x + 4 = 0. Корни 1 и 4.'],
    ['Найди сумму корней уравнения x² − 5x + 4 = 0.', 'x² − 5x + 4 = 0. Корни 1 и 4.'],
    ['Вычисли: 3/4 + 1/6.', '3/4 = 9/12. Тогда сумма равна 11/12.'],
    ['Упрости выражение (a + b)² − 2ab.', '2ab = 2 · a · b. Остаётся a² + b².'],
    // Двусмысленная запись
    ['Реши уравнение 1/2x = 4.', 'x = 8.'],
  ])('%s', (task, key) => {
    expect(mathCheck(task, key)).toBeNull()
  })
})

describe('codeNotes и mergeNotes', () => {
  const items = [
    { task: 'Реши уравнение 2x + 3 = 11.', key: 'x = 4.' },
    { task: 'Поезд прошёл 120 км за 2 ч. Найди скорость.', key: '60 км/ч.' },
    { task: 'Реши уравнение x² = 16.', key: 'x = 4.' },
  ]

  it('код берёт только математику', () => {
    expect(codeNotes('Физика', items)).toEqual([undefined, undefined, undefined])
    expect(codeNotes('математика', items)).toEqual([
      null,
      undefined,
      'Подстановка: x = −4 подходит под условие, а в ответ не входит.',
    ])
  })

  it('пометки модели встают на места заданий, которые код не взял', () => {
    const byCode = codeNotes('Математика', items)
    expect(mergeNotes(byCode, ['у проверки 50 км/ч'])).toEqual([null, 'у проверки 50 км/ч', byCode[2]])
    // Модель не ответила — остаётся то, что решил код
    expect(mergeNotes(byCode, null)).toEqual([null, null, byCode[2]])
  })
})

describe('mathCheck: вопросы о корнях', () => {
  it('считает наибольший корень, сумму, произведение и число корней', () => {
    expect(mathCheck('Найди сумму корней уравнения x² − 5x + 6 = 0.', '5. По теореме Виета.')).toEqual(ok)
    expect(mathCheck('Реши уравнение log₂(x² − 5x + 6) = 1. В ответе укажи наибольший корень.', '4.')).toEqual(ok)
    expect(mathCheck('Найди сумму квадратов всех корней уравнения x³ − 4x² − 7x + 10 = 0. В ответ запиши число.', '30.')).toEqual(ok)
    expect(mathCheck('Найди количество действительных корней уравнения 3x² + 2x + 5 = 0.', '0. D < 0.')).toEqual(ok)
    expect(
      mathCheck('Реши уравнение (log₃ x)² − 4 log₃ x + 3 = 0. Если корней несколько, в ответе запиши их сумму.', '30.'),
    ).toEqual(ok)
  })

  it('отбрасывает посторонний корень', () => {
    // x² − 4 = 5 даёт ±3, но −3 не входит в область определения
    expect(note('Реши уравнение log₅(x − 2) + log₅(x + 2) = 1. Если корней несколько, запиши их произведение.', '−9.')).toBe(
      'Пересчёт: произведение корней — 3, а в ключе −9.',
    )
  })

  it('считает целые решения неравенства', () => {
    expect(mathCheck('Найди наибольшее целое решение неравенства x² − 9 < 0.', '2.')).toEqual(ok)
    expect(note('Сколько целых решений имеет неравенство x² − 9 ≤ 0?', '5.')).toBe('Пересчёт: число целых решений — 7, а в ключе 5.')
  })

  it('отбирает корни на отрезке', () => {
    expect(mathCheck('Найди корни уравнения x² − 3x − 4 = 0, принадлежащие отрезку [0; 5].', 'x = 4.')).toEqual(ok)
    expect(note('Найди корни уравнения x² − 3x − 4 = 0, принадлежащие отрезку [0; 5].', 'x = −1 и x = 4.')).toBe(
      'Подстановка: x = −1 входит в ответ, а условию не удовлетворяет.',
    )
  })
})

describe('mathCheck: тождественные преобразования', () => {
  it('подтверждает равное выражение', () => {
    expect(mathCheck('Разложи на множители: x² − 9.', '(x − 3)(x + 3). Разность квадратов.')).toEqual(ok)
    expect(mathCheck('Упрости выражение (a + b)² − 2ab.', '(a + b)² − 2ab = a² + 2ab + b² − 2ab = a² + b².')).toEqual(ok)
    expect(mathCheck('Сократи дробь (x² − 4)/(x − 2).', 'x + 2.')).toEqual(ok)
    // Названный приём на ответ не влияет
    expect(mathCheck('Представь выражение 8a³ + 125 в виде произведения по формуле суммы кубов.', '(2a + 5)(4a² − 10a + 25).')).toEqual(ok)
    expect(mathCheck('Вычисли 21³ − 11³, используя формулу разности кубов.', '7930. 21³ − 11³ = 10 · 793.')).toEqual(ok)
  })

  it('ловит потерянный знак', () => {
    expect(note('Раскрой скобки: −3(x − 2).', '−3x − 6.')).toBe('Подстановка: при x = 2 выражение равно 0, а ответ — −12.')
    expect(note('Упрости выражение (a − b)².', 'a² − b².')).toBe('Подстановка: при a = 2, b = 5 выражение равно 9, а ответ — −21.')
  })
})

describe('mathCheck: значение выражения и системы', () => {
  it('подставляет заданные значения букв', () => {
    expect(mathCheck('Найди значение выражения 2x + 3 при x = 5.', '13.')).toEqual(ok)
    expect(note('Найди значение выражения a² − b при a = 3, b = 4.', '9 − 4 = 6.')).toBe('Пересчёт даёт 5, а в ключе 6.')
  })

  it('подставляет ответ в оба уравнения системы', () => {
    expect(mathCheck('Реши систему уравнений: x + y = 5, x − y = 1.', 'x = 3, y = 2.')).toEqual(ok)
    expect(mathCheck('Реши систему уравнений:\n2x + y = 7\nx − 3y = 0', '(3; 1).')).toEqual(ok)
    expect(note('Реши систему уравнений: x + y = 5, x − y = 1.', 'x = 2, y = 3.')).toBe(
      'Подстановка: x = 2, y = 3 не подходит к второму уравнению.',
    )
  })

  it('система неравенств с одной переменной — пересечение', () => {
    expect(mathCheck('Реши систему неравенств: x > 2, x ≤ 5.', '2 < x ≤ 5.')).toEqual(ok)
    expect(note('Реши систему неравенств: x > 2, x ≤ 5.', 'x > 2.')).toBe('Подстановка: x = 6 входит в ответ, а условию не удовлетворяет.')
  })
})

describe('mathCheck: итоговая запись result', () => {
  const task = 'Реши уравнение log₃(x + 2) = 2.'
  const key = 'x + 2 = 3² = 9, поэтому x = 7. Условие x + 2 > 0 выполнено.'

  it('выручает, когда ключ начинается с решения', () => {
    expect(mathCheck(task, key)).toBeNull()
    expect(mathCheck(task, key, 'x = 7')).toEqual(ok)
    expect(note(task, key.replace('x = 7', 'x = 11'), 'x = 11')).toBe('Подстановка: x = 7 подходит под условие, а в ответ не входит.')
  })

  it('не берётся, если запись расходится с ключом, который видит репетитор', () => {
    expect(mathCheck(task, key.replace('x = 7', 'x = 11'), 'x = 7')).toBeNull()
  })

  it('ключ, который читается сам, важнее записи', () => {
    expect(note('Реши уравнение 2x + 3 = 11.', 'x = 5.', 'x = 4')).toBe('Подстановка: x = 4 подходит под условие, а в ответ не входит.')
  })
})
