function sameTopic(exemplar: Exemplar, lessonTopic: string): boolean {
  const a = exemplar.topic.toLowerCase()
  const b = lessonTopic.toLowerCase().trim()
  return Boolean(b) && (a.includes(b) || b.includes(a))
}

function pick<T>(items: T[], random: () => number): T | undefined {
  return items.length ? items[Math.floor(random() * items.length)] : undefined
}

/**
 * Блок образцов для запроса: один из предмета урока и один из другого предмета.
 * random — для тестов: с подменённой функцией выбор повторяется.
 */
export function styleExemplars(subject: string, lessonTopic: string, random: () => number = Math.random): string {
  const allowed = (list: Exemplar[]) => list.filter((e) => !sameTopic(e, lessonTopic))
  const own = allowed(EXEMPLARS[subject] ?? [])
  const otherSubjects = Object.keys(EXEMPLARS).filter((s) => s !== subject)

  const firstSubject = own.length ? null : pick(otherSubjects, random)
  const first = own.length ? pick(own, random) : pick(allowed(EXEMPLARS[firstSubject!]), random)
  const secondSubject = pick(
    otherSubjects.filter((s) => s !== firstSubject),
    random,
  )
  const second = secondSubject ? pick(allowed(EXEMPLARS[secondSubject]), random) : undefined

  const chosen = [first, second].filter((e): e is Exemplar => Boolean(e))
  return [
    'Образцы блоков теории — из ДРУГИХ тем. Они показывают только манеру: с чего начать, как объяснить «почему», какой длины p и rule. Не бери из них примеры, числа, сравнения и начала предложений: для темы урока придумай свои.',
    ...chosen.map(({ h, p, rule, ex }) => JSON.stringify({ h, p, rule, ex })),
  ].join('\n')
}

function shingles(text: string, size = 5): Set<string> {
  const words = text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .split(/\s+/)
    .filter(Boolean)
  const result = new Set<string>()
  for (let i = 0; i + size <= words.length; i++) result.add(words.slice(i, i + size).join(' '))
  return result
}

// Каждый образец отдельно: склейка дала бы «фразы» из конца одного и начала другого
const EXEMPLAR_SHINGLES = new Set(
  Object.values(EXEMPLARS)
    .flat()
    .flatMap((e) => [...shingles(e.p)]),
)

/**
 * Первые пять слов подряд, совпавшие с образцом, или null.
 * Совпало — модель переписала образец: блок стоит сгенерировать заново.
 */
export function copiedFragment(text: string): string | null {
  for (const s of shingles(text)) if (EXEMPLAR_SHINGLES.has(s)) return s
  return null
}
