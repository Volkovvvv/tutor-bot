function sameTopic(exemplar: Exemplar, lessonTopic: string): boolean {
  const topic = lessonTopic.toLowerCase()
  return exemplar.keys.some((key) => topic.includes(key))
}

function pick<T>(items: T[], random: () => number): T | undefined {
  return items.length ? items[Math.floor(random() * items.length)] : undefined
}

/**
 * Блок образцов для запроса: один из предмета урока и один из другого предмета.
 * random — для тестов: с подменённой функцией выбор повторяется.
 */
export function styleExemplars(subject: string, lessonTopic: string, random: () => number = Math.random): string {
  const allowed = (s: string) => (EXEMPLARS[s] ?? []).filter((e) => !sameTopic(e, lessonTopic))
  const own = pick(allowed(subject), random)
  const others = Object.keys(EXEMPLARS).filter((s) => s !== subject && allowed(s).length > 0)

  const chosen: Exemplar[] = own ? [own] : []
  while (chosen.length < 2 && others.length > 0) {
    const [s] = others.splice(Math.floor(random() * others.length), 1)
    chosen.push(pick(allowed(s), random)!)
  }

  return [
    'Образцы теории — из ДРУГИХ тем. Пиши так же просто и в том же духе: мысль своими словами, пример из жизни, ошибки-заблуждения. Не бери из них примеры, числа, сравнения и фразы: для темы урока придумай свои.',
    ...chosen.map(({ topic, theory, mistakes }) => `Тема «${topic}»: ${JSON.stringify({ theory, mistakes })}`),
  ].join('\n')
}

function shingles(text: string, size = 5): Set<string> {
  const words = text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .split(/\s+/)
    .filter(Boolean)
  const result = new Set<string>()
  for (let i = 0; i + size <= words.length; i++) result.add(words.slice(i, i + size).join(' '))
  return result
}

// Каждый блок отдельно: склейка дала бы «фразы» из конца одного и начала другого
const EXEMPLAR_SHINGLES = new Set(
  Object.values(EXEMPLARS)
    .flat()
    .flatMap((e) => e.theory)
    .flatMap((block) => [...shingles(block.p)]),
)

/**
 * Первые пять слов подряд, совпавшие с образцом, или null.
 * Совпало — модель переписала образец: блок стоит сгенерировать заново.
 */
export function copiedFragment(text: string): string | null {
  for (const s of shingles(text)) if (EXEMPLAR_SHINGLES.has(s)) return s
  return null
}
