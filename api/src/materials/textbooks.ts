/**
 * Блок для промпта или null, если карточки учебника для ученика нет.
 *
 * withTopics: false — когда порядок тем уже дала карточка программы:
 * от учебника остаются только формулировки.
 */
export function textbook(country: Country, subject: string, grade: number | null, withTopics = true): string | null {
  const book = grade ? TEXTBOOKS[country]?.[subject]?.[grade] : undefined
  if (!book) return null
  if (!withTopics) {
    return [
      `Учебник ученика — ${book.title}. Учебник определяет только формулировки: правила и термины давай так, как в нём. Какие темы входят в класс, решает программа выше. Задания составляй свои, такого же уровня.`,
      ...book.chapters.map((c) => `«${c.title}»: ${c.wording}`),
      `В целом: ${book.notes}`,
    ].join('\n')
  }
  return [
    `Учебник ученика — ${book.title}. Главы и темы идут в том порядке, в каком их проходят в школе. Найди, к какой теме относится урок: всё, что стоит раньше, ученик уже знает, на это можно опираться; тем, которые стоят позже, он ещё не проходил — не используй их в объяснении и в заданиях. Термины и правила давай в формулировках учебника. Задания составляй свои, такого же уровня.`,
    ...book.chapters.flatMap((c, i) => [`Глава ${i + 1}. ${c.title}: ${c.topics.join('; ')}.`, `Как в учебнике: ${c.wording}`]),
    `В целом: ${book.notes}`,
  ].join('\n')
}
