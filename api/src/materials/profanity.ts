/**
 * Грубый фильтр мата и порно в теме и пожеланиях — до запроса к ИИ.
 *
 * Не заменяет отказ модели (см. refuse в промпте), а дополняет его: обрывает
 * очевидное сразу, не тратя ни деньги на запрос, ни пробный лимит репетитора.
 *
 * Слова ищутся по началу слова (основа + допустимые приставки), а не по подстроке:
 * «страхуй», «хулиган», «мандарин», «педикюр» должны проходить. Осторожные слова
 * вроде «негр», «нигер» (страна), «жид» (история) сюда намеренно не входят.
 */

// Латиница, похожая на кириллицу: «xуй», «пиzда» не должны обходить фильтр
const LOOKALIKE: Record<string, string> = {
  a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у', z: 'з', i: 'и', n: 'п',
}

// Приставки, с которыми матерное слово остаётся матерным: «нахуй», «заебись», «распиздяй»
const PRE = '(?:на|по|до|за|при|от|вы|раз|рас|об|не|ни|о|в|с|у|пере|под|недо|съ|объ|разъ)?'

// Начала слов; проверяются у каждого слова целиком, с начала
const RU: RegExp[] = [
  new RegExp(`^${PRE}ху(?:й|я|е|ё|и)`), // хуй, хуя, хуе…, нахуй, похуй
  new RegExp(`^${PRE}пизд`),
  new RegExp(`^${PRE}[её]б(?:а|у|л[аои]|н[уиы]|и[сл]|ё|е[тшм]|ун|ыр)`), // ебать, заебись, ебло
  /^бл(?:я(?:д|т|ть)|ё)/, // блять, блядь, но не «бляха»
  /^муд(?:ак|ил|ач|озв|ло)/, // мудак, мудила, но не «мудрый»
  /^пид[оа]р/,
  /^пидр/,
  /^педераст/,
  /^педики?$/, // но не «педикюр»
  /^г[ао]ндон/,
  /^шлюх/,
  /^залуп/,
  /^манд(?:а|у|е|ой|ы)$/, // но не «мандарин», «мандат»
  /^дроч(?:и|ить|ил|ка|ун|ёр|ер)/,
  /^говн/,
  /^(?:сука|суку|суки|сучка|сучара|сучонок)$/,
  /^(?:порно|хентай|порнуха|порнография)/,
  /^ебал/,
]

// Слова с цензурной звёздочкой: «х*й», «п*зда», «бл*ть»
const CENSORED = /(?:^|[^\p{L}])(?:х[*]й|п[*]зд|бл[*][дт]|[*]уй|[*]изд|е[*]ат)/u

const EN: RegExp[] = [/^fuck/, /^motherfuck/, /^shit(?!ake|tim)/, /^bitch/, /^cunt/, /^whore/, /^asshole/, /^nigger/, /^niggas?$/, /^porn/, /^pussy/, /^pizd/, /^blya[dt]/, /^huy(?:[^g]|$)/, /^ebat/]

function hasLookalike(word: string): string | null {
  if (!/[a-z]/.test(word) || !/[а-я]/.test(word)) return null
  return word.replace(/[a-z]/g, (c) => LOOKALIKE[c] ?? c)
}

function badWord(word: string): boolean {
  const w = word.replace(/ё/g, 'е')
  const mapped = hasLookalike(w)
  for (const re of RU) {
    // Шаблоны написаны с «ё» там, где она нужна, поэтому проверяем и исходное слово
    if (re.test(word) || re.test(w) || (mapped !== null && re.test(mapped))) return true
  }
  return EN.some((re) => re.test(word))
}

/** Есть ли в тексте мат или порно. Пустой и обычный школьный текст — нет. */
export function hasProfanity(text: string): boolean {
  const lower = text.toLowerCase()
  if (CENSORED.test(lower)) return true

  // Слова: буквы и звёздочка внутри слова (она нужна шаблону CENSORED, поэтому
  // из слова не вырезаем, а в обычных шаблонах она просто не совпадёт).
  const words = lower.match(/[\p{L}]+/gu) ?? []
  if (words.some(badWord)) return true

  // Буквы вразрядку: «х у й», «п.и.з.д.а» — склеиваем цепочки одиночных букв
  const spaced = lower.match(/(?:^|[^\p{L}])((?:\p{L}[\s.\-_*,]+){2,}\p{L})(?![\p{L}])/gu) ?? []
  return spaced.some((chunk) => badWord(chunk.replace(/[^\p{L}]/gu, '')))
}
