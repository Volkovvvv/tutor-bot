import { hasProfanity } from './profanity'

describe('hasProfanity', () => {
  it('ловит мат в разных формах', () => {
    for (const bad of [
      'хуй', 'иди нахуй', 'похуй на тему', 'пиздец', 'ёбаный урок', 'заебись', 'блять', 'блядь',
      'ты мудак', 'пидор', 'шлюха', 'сука', 'говно', 'залупа', 'порно', 'хентай', 'fuck you', 'shit',
    ]) {
      expect(hasProfanity(bad)).toBe(true)
    }
  })

  it('ловит обход: латиница, вразрядку, звёздочки, регистр', () => {
    for (const bad of ['xуй', 'ПИЗДА', 'х у й', 'п.и.з.д.а', 'х*й', 'бл*ть', 'пиzда', 'Хуйня']) {
      expect(hasProfanity(bad)).toBe(true)
    }
  })

  it('пропускает школьные темы и похожие слова', () => {
    for (const ok of [
      'Квадратные уравнения', 'Теорема Пифагора', 'страхуй и хулиган', 'Хутор и художник', 'мандарин и мандат',
      'педикюр', 'мудрость и мудрый', 'небо, ребро и ребус', 'требуй потребителя', 'Нигер: страна и река',
      'гондола и гандбол', 'шлюз и шлюпка', 'бляха', 'оскорбление', 'скипидар', 'залив', 'Хуан Карлос',
      'Present Simple vs Past Simple', 'Shakespeare, Dickens and Cockney', 'ассимиляция', 'Сук и сучок',
      'Huygens principle', 'Правописание: Н и НН в причастиях', 'Ёж и ёлка', 'Бытие и сознание', 'ёмкость и объём',
    ]) {
      expect([ok, hasProfanity(ok)]).toEqual([ok, false])
    }
  })

  it('пустая строка — не мат', () => {
    expect(hasProfanity('')).toBe(false)
  })
})
