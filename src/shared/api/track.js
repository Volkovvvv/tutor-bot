import { api } from './client.js'

// События, которых не видит сервер: оценка материала, заявка на «больше материалов».
// Всё остальное сервер пишет сам. Статистика вторична: сбой сети не должен
// ни показывать ошибку, ни мешать действию, из-за которого она отправлена.
export function track(name, props) {
  return api.post('/events', { name, props }).catch(() => {})
}
